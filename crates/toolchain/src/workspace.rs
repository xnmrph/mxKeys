//! The west workspace (ZMK + Zephyr + modules), generated from the user's
//! `config/west.yml` and kept in app data — nothing is written into the user's repo.
//!
//! The generated manifest keeps the user's projects, remotes and revisions, and adds a
//! `name-allowlist` to ZMK's import so only what an nRF52840 build needs is fetched
//! (verified byte-identical firmware; 3.0 GB → 1.2 GB). `full = true` skips the filter.

use std::fs;
use std::path::{Path, PathBuf};

use serde::Serialize;
use serde_yaml::{Mapping, Value};
use sha2::{Digest, Sha256};

use crate::install::{Installed, Progress};
use crate::manifest::Manifest;
use crate::runner::{Cmd, CommandRunner, RunError};

#[derive(Debug, thiserror::Error)]
pub enum WorkspaceError {
    #[error("config/west.yml can't be read: {0}")]
    Yaml(#[from] serde_yaml::Error),
    #[error("config/west.yml has no `manifest:` section")]
    NoManifest,
    #[error("config/west.yml doesn't include ZMK, so there's nothing to build")]
    NoZmk,
    #[error(transparent)]
    Run(#[from] RunError),
    #[error("couldn't write {path}: {source}")]
    Io { path: PathBuf, source: std::io::Error },
}

const HEADER: &str =
    "# Generated by mxKeys from your config/west.yml — don't edit; edit your repo instead.\n";

fn key(s: &str) -> Value {
    Value::String(s.to_string())
}

fn is_zmk(p: &Mapping) -> bool {
    let name = p.get(key("name")).and_then(Value::as_str);
    let url = p.get(key("url")).and_then(Value::as_str);
    let repo = p.get(key("repo-path")).and_then(Value::as_str);
    name == Some("zmk")
        || repo == Some("zmk")
        || url.is_some_and(|u| u.trim_end_matches('/').trim_end_matches(".git").ends_with("/zmk"))
}

/// Generate the workspace manifest from the user's west.yml text.
pub fn generate_manifest(
    user_west_yml: &str,
    allowlist: Option<&[String]>,
) -> Result<String, WorkspaceError> {
    let mut doc: Value = serde_yaml::from_str(user_west_yml)?;
    let manifest = doc
        .get_mut("manifest")
        .and_then(Value::as_mapping_mut)
        .ok_or(WorkspaceError::NoManifest)?;

    // Our copy lives in `<workspace>/config/west.yml`.
    let mut self_map = manifest
        .get(key("self"))
        .and_then(Value::as_mapping)
        .cloned()
        .unwrap_or_default();
    self_map.insert(key("path"), key("config"));
    manifest.insert(key("self"), Value::Mapping(self_map));

    let projects = manifest
        .get_mut(key("projects"))
        .and_then(Value::as_sequence_mut)
        .ok_or(WorkspaceError::NoZmk)?;
    let zmk = projects
        .iter_mut()
        .filter_map(Value::as_mapping_mut)
        .find(|p| is_zmk(p))
        .ok_or(WorkspaceError::NoZmk)?;
    if let Some(allow) = allowlist {
        let import = zmk.get(key("import")).cloned();
        let mut map = match import {
            Some(Value::String(file)) => {
                let mut m = Mapping::new();
                m.insert(key("file"), key(&file));
                m
            }
            Some(Value::Mapping(m)) => m,
            Some(Value::Bool(true)) | None => {
                let mut m = Mapping::new();
                m.insert(key("file"), key("app/west.yml"));
                m
            }
            Some(other) => {
                let mut m = Mapping::new();
                m.insert(key("file"), other);
                m
            }
        };
        if !map.contains_key(key("name-allowlist")) {
            map.insert(
                key("name-allowlist"),
                Value::Sequence(allow.iter().map(|s| key(s)).collect()),
            );
        }
        zmk.insert(key("import"), Value::Mapping(map));
    }
    Ok(format!("{HEADER}{}", serde_yaml::to_string(&doc)?))
}

/// A workspace directory, keyed by the generated manifest (same ZMK + modules → shared).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Workspace {
    pub dir: PathBuf,
    pub manifest_text: String,
}

impl Workspace {
    pub fn for_manifest(data: &Path, manifest_text: &str) -> Workspace {
        let id = &hex::encode(Sha256::digest(manifest_text.as_bytes()))[..12];
        Workspace {
            dir: data.join("workspaces").join(id),
            manifest_text: manifest_text.to_string(),
        }
    }
    pub fn zephyr_cmake_dir(&self) -> PathBuf {
        self.dir
            .join("zephyr")
            .join("share")
            .join("zephyr-package")
            .join("cmake")
    }
    pub fn zmk_app(&self) -> PathBuf {
        self.dir.join("zmk").join("app")
    }
    fn ready_marker(&self) -> PathBuf {
        self.dir.join(".mxkeys-ready")
    }
    pub fn is_ready(&self) -> bool {
        self.ready_marker().is_file()
    }
    /// Resolved commits, written after every update (`<name> <sha>` lines).
    pub fn lock_file(&self) -> PathBuf {
        self.dir.join("mxkeys-lock.txt")
    }
}

fn io(path: &Path) -> impl FnOnce(std::io::Error) -> WorkspaceError + '_ {
    move |source| WorkspaceError::Io {
        path: path.to_path_buf(),
        source,
    }
}

/// Create/update the workspace: `west init -l`, shallow `west update`, then the Python
/// requirements Zephyr and the modules need. `force_update` re-fetches (e.g. to pick up
/// the latest ZMK on a moving branch).
pub fn prepare(
    ws: &Workspace,
    tools: &Installed,
    manifest: &Manifest,
    runner: &dyn CommandRunner,
    force_update: bool,
    progress: &mut dyn FnMut(Progress),
) -> Result<(), WorkspaceError> {
    if ws.is_ready() && !force_update {
        return Ok(());
    }
    let env = tools.env();
    let west = tools.layout.west();
    let config = ws.dir.join("config");
    fs::create_dir_all(&config).map_err(io(&config))?;
    fs::write(config.join("west.yml"), &ws.manifest_text).map_err(io(&config))?;
    let mut line = |t: &str| progress(Progress::Line { text: t.to_string() });

    if !ws.dir.join(".west").is_dir() {
        runner.run(
            &Cmd::new(&west)
                .args(["init", "-l", "config"])
                .cwd(&ws.dir)
                .envs(&env),
            &mut line,
        )?;
    }
    runner.run(
        &Cmd::new(&west)
            .args([
                "update",
                "--narrow",
                &format!("--fetch-opt=--depth={}", manifest.workspace.clone_depth),
            ])
            .cwd(&ws.dir)
            .envs(&env),
        &mut line,
    )?;
    let reqs: Vec<String> = manifest
        .python
        .workspace_requirements
        .iter()
        .map(|r| ws.dir.join(r))
        .filter(|p| p.is_file())
        .flat_map(|p| ["-r".to_string(), p.display().to_string()])
        .collect();
    if !reqs.is_empty() {
        runner.run(
            &Cmd::new(tools.layout.venv_python())
                .args(["-m", "pip", "install", "--quiet"])
                .args(reqs)
                .envs(&env),
            &mut line,
        )?;
    }
    // Resolved commits for every project except the (non-git) manifest folder itself.
    let mut names: Vec<String> = Vec::new();
    runner.run(
        &Cmd::new(&west)
            .args(["list", "-f", "{name}"])
            .cwd(&ws.dir)
            .envs(&env),
        &mut |l: &str| {
            let n = l.trim();
            if !n.is_empty() && n != "manifest" {
                names.push(n.to_string());
            }
        },
    )?;
    let mut lock = String::new();
    runner.run(
        &Cmd::new(&west)
            .args(["list", "-f", "{name} {sha}"])
            .args(names)
            .cwd(&ws.dir)
            .envs(&env),
        &mut |l: &str| {
            lock.push_str(l);
            lock.push('\n');
        },
    )?;
    fs::write(ws.lock_file(), lock).map_err(io(&ws.dir))?;
    fs::write(ws.ready_marker(), "").map_err(io(&ws.dir))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::runner::MockRunner;

    const OWNER: &str = "manifest:\n  remotes:\n    - name: urob\n      url-base: https://github.com/urob\n    - name: zmkfirmware\n      url-base: https://github.com/zmkfirmware\n  projects:\n    - name: zmk\n      remote: zmkfirmware\n      revision: main\n      import: app/west.yml\n    - name: zmk-helpers\n      remote: urob\n      revision: main\n  self:\n    path: config\n";

    #[test]
    fn generated_manifest_adds_allowlist_and_keeps_everything_else() {
        let allow = vec!["zephyr".to_string(), "hal_nordic".to_string()];
        let text = generate_manifest(OWNER, Some(&allow)).unwrap();
        assert!(text.starts_with(HEADER));
        let v: Value = serde_yaml::from_str(&text).unwrap();
        let p = &v["manifest"]["projects"];
        assert_eq!(p[0]["import"]["file"], key("app/west.yml"));
        assert_eq!(p[0]["import"]["name-allowlist"][1], key("hal_nordic"));
        assert_eq!(p[0]["revision"], key("main"));
        assert_eq!(p[1]["name"], key("zmk-helpers"));
        assert_eq!(v["manifest"]["self"]["path"], key("config"));

        let full = generate_manifest(OWNER, None).unwrap();
        let v: Value = serde_yaml::from_str(&full).unwrap();
        assert_eq!(v["manifest"]["projects"][0]["import"], key("app/west.yml"));
    }

    #[test]
    fn import_forms_and_errors() {
        let allow = vec!["zephyr".to_string()];
        let map_form = OWNER.replace(
            "import: app/west.yml",
            "import:\n        file: app/west.yml\n        name-blocklist: [x]",
        );
        let v: Value = serde_yaml::from_str(&generate_manifest(&map_form, Some(&allow)).unwrap()).unwrap();
        assert_eq!(
            v["manifest"]["projects"][0]["import"]["name-blocklist"][0],
            key("x")
        );
        assert_eq!(
            v["manifest"]["projects"][0]["import"]["name-allowlist"][0],
            key("zephyr")
        );
        let url_form = OWNER.replace(
            "name: zmk\n      remote: zmkfirmware",
            "name: firmware\n      url: https://gitea.example/me/zmk.git",
        );
        assert!(generate_manifest(&url_form, Some(&allow)).is_ok());
        assert!(matches!(
            generate_manifest("foo: 1", None),
            Err(WorkspaceError::NoManifest)
        ));
        let no_zmk = OWNER.replace("name: zmk\n", "name: other\n");
        assert!(matches!(
            generate_manifest(&no_zmk, None),
            Err(WorkspaceError::NoZmk)
        ));
    }

    #[test]
    fn same_manifest_same_workspace() {
        let a = Workspace::for_manifest(Path::new("/d"), "x");
        assert_eq!(a, Workspace::for_manifest(Path::new("/d"), "x"));
        assert_ne!(a.dir, Workspace::for_manifest(Path::new("/d"), "y").dir);
    }

    #[test]
    fn prepare_runs_the_right_commands() {
        let m = Manifest::embedded();
        let data = std::env::temp_dir().join(format!("mxkeys-ws-{}", std::process::id()));
        let _ = fs::remove_dir_all(&data);
        let tools = Installed {
            layout: crate::install::Layout::new(&data, &m, crate::host::Host::current().unwrap()),
            git_dir: None,
        };
        let ws = Workspace::for_manifest(&data, "manifest: {}\n");
        let runner = MockRunner::default();
        runner.on("list -f \"{name} {sha}\"", &["zmk abc123", "zephyr def456"], true);
        runner.on("list -f {name}", &["manifest", "zmk", "zephyr"], true);
        prepare(&ws, &tools, &m, &runner, false, &mut |_| {}).unwrap();
        let cmds = runner.commands();
        assert!(cmds[0].ends_with("init -l config"), "{cmds:?}");
        assert!(cmds[1].contains("update --narrow --fetch-opt=--depth=1"));
        assert!(cmds[2].ends_with("list -f {name}"), "{cmds:?}");
        assert!(
            cmds[3].ends_with("list -f \"{name} {sha}\" zmk zephyr"),
            "{cmds:?}"
        );
        assert_eq!(
            fs::read_to_string(ws.lock_file()).unwrap(),
            "zmk abc123\nzephyr def456\n"
        );
        assert!(ws.is_ready());
        // Ready → nothing to do.
        prepare(&ws, &tools, &m, &runner, false, &mut |_| {}).unwrap();
        assert_eq!(runner.commands().len(), 4);
        fs::remove_dir_all(&data).unwrap();
    }
}
