pub const HEADER: &str = r#"/* Generated by mxKeys. SPDX-License-Identifier: MIT */
#pragma once

#include <stdbool.h>
#include <stdint.h>
#include <lvgl.h>

struct mxkeys_art {
    const lv_image_dsc_t *const *frames;
    const uint16_t *delays_ms;
    uint16_t count;
};

/* The frames for this half (count == 0: nothing to show). */
extern const struct mxkeys_art mxkeys_art;
"#;

pub const ART_C: &str = r#"/*
 * Generated by mxKeys: shows the pictures from frames.c on the nice!view, on top of
 * ZMK's own status screen. Edit the pictures in mxKeys rather than here.
 *
 * SPDX-License-Identifier: MIT
 */

#include <zephyr/init.h>
#include <zephyr/kernel.h>
#include <lvgl.h>

#include <zmk/display.h>
#include <zmk/event_manager.h>
#include <zmk/events/activity_state_changed.h>

#include "mxkeys_art.h"

static lv_obj_t *mxk_img;
static lv_timer_t *mxk_timer;
static uint16_t mxk_frame;
static bool mxk_active = true;

static void mxk_next(lv_timer_t *timer) {
    mxk_frame = (mxk_frame + 1) % mxkeys_art.count;
    lv_image_set_src(mxk_img, mxkeys_art.frames[mxk_frame]);
    lv_timer_set_period(timer, mxkeys_art.delays_ms[mxk_frame]);
}

/* Runs on the display work queue, after ZMK has loaded its status screen. */
static void mxk_show(struct k_work *work) {
    lv_obj_t *screen = lv_screen_active();
    if (screen == NULL || mxkeys_art.count == 0) {
        return;
    }
    mxk_img = lv_image_create(screen);
    lv_image_set_src(mxk_img, mxkeys_art.frames[0]);
    lv_obj_align(mxk_img, LV_ALIGN_TOP_LEFT, 0, 0);
    if (mxkeys_art.count > 1) {
        mxk_timer = lv_timer_create(mxk_next, mxkeys_art.delays_ms[0], NULL);
        if (!mxk_active) {
            lv_timer_pause(mxk_timer);
        }
    }
}
K_WORK_DEFINE(mxk_show_work, mxk_show);

/* Wait until ZMK's display is ready, then queue mxk_show behind its set-up. */
static void mxk_wait(struct k_work *work);
K_WORK_DELAYABLE_DEFINE(mxk_wait_work, mxk_wait);
static void mxk_wait(struct k_work *work) {
    if (zmk_display_is_initialized()) {
        k_work_submit_to_queue(zmk_display_work_q(), &mxk_show_work);
    } else {
        k_work_schedule(&mxk_wait_work, K_MSEC(100));
    }
}

static int mxk_init(void) {
    if (mxkeys_art.count > 0) {
        k_work_schedule(&mxk_wait_work, K_MSEC(100));
    }
    return 0;
}
SYS_INIT(mxk_init, APPLICATION, CONFIG_APPLICATION_INIT_PRIORITY);

/* Pause the animation while the keyboard is idle (saves battery). */
static void mxk_activity(struct k_work *work) {
    if (mxk_timer == NULL) {
        return;
    }
    if (mxk_active) {
        lv_timer_resume(mxk_timer);
    } else {
        lv_timer_pause(mxk_timer);
    }
}
K_WORK_DEFINE(mxk_activity_work, mxk_activity);

static int mxk_activity_listener(const zmk_event_t *eh) {
    const struct zmk_activity_state_changed *ev = as_zmk_activity_state_changed(eh);
    if (ev == NULL) {
        return ZMK_EV_EVENT_BUBBLE;
    }
    mxk_active = ev->state == ZMK_ACTIVITY_ACTIVE;
    if (zmk_display_is_initialized()) {
        k_work_submit_to_queue(zmk_display_work_q(), &mxk_activity_work);
    }
    return ZMK_EV_EVENT_BUBBLE;
}
ZMK_LISTENER(mxk_art_activity, mxk_activity_listener);
ZMK_SUBSCRIPTION(mxk_art_activity, zmk_activity_state_changed);
"#;

fn c_frames(name: &str, frames: &[Frame]) -> String {
    let mut s = String::new();
    for (i, f) in frames.iter().enumerate() {
        let (w, h) = lvgl::display_size(f);
        let bits = lvgl::pack(f);
        s += &format!("static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}_{i}_map[] = {{\n    MXK_PALETTE\n");
        for chunk in bits.chunks(16) {
            s += "    ";
            s += &chunk
                .iter()
                .map(|b| format!("0x{b:02x},"))
                .collect::<Vec<_>>()
                .join(" ");
            s += "\n";
        }
        s += "};\n";
        s += &format!(
            "static const lv_image_dsc_t {name}_{i} = {{\n    .header.cf = LV_COLOR_FORMAT_I1,\n    .header.w = {w},\n    .header.h = {h},\n    .data_size = {},\n    .data = {name}_{i}_map,\n}};\n\n",
            lvgl::frame_bytes(f)
        );
    }
    let list = (0..frames.len())
        .map(|i| format!("&{name}_{i}"))
        .collect::<Vec<_>>()
        .join(", ");
    let delays = frames
        .iter()
        .map(|f| f.delay_ms.clamp(20, 60_000).to_string())
        .collect::<Vec<_>>()
        .join(", ");
    if frames.is_empty() {
        s += "const struct mxkeys_art mxkeys_art = { .frames = NULL, .delays_ms = NULL, .count = 0 };\n";
    } else {
        s += &format!(
            "static const lv_image_dsc_t *const {name}_frames[] = {{ {list} }};\nstatic const uint16_t {name}_delays[] = {{ {delays} }};\nconst struct mxkeys_art mxkeys_art = {{ .frames = {name}_frames, .delays_ms = {name}_delays, .count = {} }};\n",
            frames.len()
        );
    }
    s
}

/// `frames.c` for both halves. The left half is ZMK's central (`ZMK_SPLIT_ROLE_CENTRAL`),
/// the right half the peripheral — as in the Corne profile.
pub fn frames_c(left: &[Frame], right: &[Frame]) -> String {
    format!(
        r#"/*
 * Generated by mxKeys — the nice!view pictures (1-bit LVGL images, already turned
 * to the display's orientation). Edit them in mxKeys; this file is rewritten.
 *
 * SPDX-License-Identifier: MIT
 */

#include <zephyr/sys/util.h>
#include <lvgl.h>

#include "mxkeys_art.h"

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

/* Bit set = a light pixel. The nice!view shows LVGL "black" as light (its status
 * screen draws on a black background that looks light), so index 1 is black.
 * Pictures look exactly like the mxKeys preview, whatever the screen colour
 * setting; each picture has its own Invert option. */
#define MXK_PALETTE 0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff,

#if IS_ENABLED(CONFIG_ZMK_SPLIT) && !IS_ENABLED(CONFIG_ZMK_SPLIT_ROLE_CENTRAL)
/* Right half: {} frame(s) */
{}
#else
/* Left half: {} frame(s) */
{}
#endif
"#,
        right.len(),
        c_frames("mxk_right", right),
        left.len(),
        c_frames("mxk_left", left),
    )
}

pub fn readme(cfg: &ArtConfig) -> String {
    let describe = |h: &HalfArt| match h.mode {
        Mode::Off => "ZMK's own screen".to_string(),
        Mode::Art => format!(
            "a picture in the art area ({})",
            h.source.as_deref().unwrap_or("?")
        ),
        Mode::Full => format!("a full-screen picture ({})", h.source.as_deref().unwrap_or("?")),
    };
    format!(
        "# nice!view pictures\n\nMade with mxKeys. Left half: {}. Right half: {}.\n\n\
The originals are in `source/`, the settings in `mxkeys.json`. `src/frames.c` is generated —\n\
change the pictures in mxKeys (or delete this folder and the `cmake`/`kconfig` lines in\n\
`zephyr/module.yml` to go back to the stock screen). Turn the pictures off without\n\
deleting anything with `CONFIG_MXKEYS_NICE_VIEW_ART=n` in your `.conf`.\n",
        describe(&cfg.left),
        describe(&cfg.right)
    )
}

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum ModuleYmlError {
    #[error("zephyr/module.yml already builds other code (`{0}:`), so mxKeys can't add its own. Add `add_subdirectory(nice_view_art)` to that CMakeLists.txt and `rsource \"nice_view_art/Kconfig\"` to that Kconfig by hand.")]
    Conflict(String),
}

const CMAKE_LINE: &str = "cmake: nice_view_art";
const KCONFIG_LINE: &str = "kconfig: nice_view_art/Kconfig";

/// `zephyr/module.yml` with mxKeys' `cmake`/`kconfig` entries added (lossless edit:
/// only two lines are inserted under `build:`).
pub fn add_to_module_yml(existing: Option<&str>) -> Result<String, ModuleYmlError> {
    let Some(text) = existing.filter(|t| !t.trim().is_empty()) else {
        return Ok(format!("build:\n  {CMAKE_LINE}\n  {KCONFIG_LINE}\n"));
    };
    let nl = if text.contains("\r\n") { "\r\n" } else { "\n" };
    let lines: Vec<&str> = text.split_inclusive('\n').collect();
    let build = lines.iter().position(|l| l.trim_end() == "build:");
    let Some(b) = build else {
        let sep = if text.ends_with('\n') { "" } else { nl };
        return Ok(format!(
            "{text}{sep}build:{nl}  {CMAKE_LINE}{nl}  {KCONFIG_LINE}{nl}"
        ));
    };
    // Children of `build:` (indented lines until the next top-level key).
    let children: Vec<&str> = lines[b + 1..]
        .iter()
        .take_while(|l| l.trim().is_empty() || l.starts_with([' ', '\t']))
        .copied()
        .collect();
    let indent = children
        .iter()
        .find(|l| !l.trim().is_empty())
        .map(|l| &l[..l.len() - l.trim_start().len()])
        .unwrap_or("  ")
        .to_string();
    let has = |key: &str| {
        children.iter().any(|l| {
            l.trim_start().starts_with(&format!("{key}:"))
                && l.starts_with(&indent)
                && !l[indent.len()..].starts_with([' ', '\t'])
        })
    };
    let ours = children.iter().any(|l| l.trim() == CMAKE_LINE);
    if ours {
        return Ok(text.to_string());
    }
    for key in ["cmake", "kconfig"] {
        if has(key) {
            return Err(ModuleYmlError::Conflict(key.into()));
        }
    }
    let mut out = String::new();
    for (i, l) in lines.iter().enumerate() {
        out += l;
        if i == b {
            if !l.ends_with('\n') {
                out += nl;
            }
            out += &format!("{indent}{CMAKE_LINE}{nl}{indent}{KCONFIG_LINE}{nl}");
        }
    }
    Ok(out)
}

/// `zephyr/module.yml` without mxKeys' entries; `None` if nothing else is left (the
/// file can be deleted — mxKeys created it).
pub fn remove_from_module_yml(text: &str) -> Option<String> {
    let kept: String = text
        .split_inclusive('\n')
        .filter(|l| l.trim() != CMAKE_LINE && l.trim() != KCONFIG_LINE)
        .collect();
    let only_build = kept.lines().all(|l| l.trim().is_empty() || l.trim() == "build:");
    (!only_build).then_some(kept)
}

/// Every file to write (path relative to the repo root, contents), except the
/// source pictures and `zephyr/module.yml`.
pub fn generated_files(cfg: &ArtConfig, left: &[Frame], right: &[Frame]) -> Vec<(String, Vec<u8>)> {
    let p = |f: &str| format!("{DIR}/{f}");
    vec![
        (
            p("mxkeys.json"),
            (serde_json::to_string_pretty(cfg).expect("config serialises") + "\n").into_bytes(),
        ),
        (p("CMakeLists.txt"), CMAKELISTS.as_bytes().to_vec()),
        (p("Kconfig"), KCONFIG.as_bytes().to_vec()),
        (p("README.md"), readme(cfg).into_bytes()),
        (p("src/mxkeys_art.h"), HEADER.as_bytes().to_vec()),
        (p("src/art.c"), ART_C.as_bytes().to_vec()),
        (p("src/frames.c"), frames_c(left, right).into_bytes()),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn module_yml_edits() {
        assert_eq!(
            add_to_module_yml(None).unwrap(),
            "build:\n  cmake: nice_view_art\n  kconfig: nice_view_art/Kconfig\n"
        );
        // The owner's file (zmk-config template).
        let owner = "build:\n  settings:\n    board_root: .\n";
        let added = add_to_module_yml(Some(owner)).unwrap();
        assert_eq!(added, "build:\n  cmake: nice_view_art\n  kconfig: nice_view_art/Kconfig\n  settings:\n    board_root: .\n");
        assert_eq!(add_to_module_yml(Some(&added)).unwrap(), added, "idempotent");
        assert_eq!(remove_from_module_yml(&added).as_deref(), Some(owner));
        assert_eq!(remove_from_module_yml(&add_to_module_yml(None).unwrap()), None);
        assert_eq!(
            add_to_module_yml(Some("name: x\nbuild:\n  cmake: .\n")),
            Err(ModuleYmlError::Conflict("cmake".into()))
        );
        assert_eq!(
            add_to_module_yml(Some("name: x")).unwrap(),
            "name: x\nbuild:\n  cmake: nice_view_art\n  kconfig: nice_view_art/Kconfig\n"
        );
    }

    #[test]
    fn frames_c_has_both_halves() {
        let f = Frame {
            width: 68,
            height: 160,
            pixels: vec![true; 68 * 160],
            delay_ms: 150,
        };
        let c = frames_c(&[f.clone(), f], &[]);
        assert!(c.contains("const struct mxkeys_art mxkeys_art = { .frames = mxk_left_frames, .delays_ms = mxk_left_delays, .count = 2 };"));
        assert!(c.contains(
            "const struct mxkeys_art mxkeys_art = { .frames = NULL, .delays_ms = NULL, .count = 0 };"
        ));
        assert!(c.contains(".header.w = 160,\n    .header.h = 68,\n    .data_size = 1368,"));
        assert!(c.contains("static const uint16_t mxk_left_delays[] = { 150, 150 };"));
        // All-light frames plus the 5 0xff bytes in the palette macro (white, then
        // black's alpha): bit set = light on the nice!view = LVGL black.
        assert_eq!(c.matches("0xff,").count(), 2 * 20 * 68 + 5);
        assert!(c.contains("#define MXK_PALETTE 0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff,"));
    }

    #[test]
    fn budget() {
        assert_eq!(max_frames(Area::Full, 64), 65536 / (1368 + 32));
        assert_eq!(max_frames(Area::Art, 64), 65536 / (1232 + 32));
        assert_eq!(
            max_frames(Area::Full, 10_000),
            max_frames(Area::Full, MAX_BUDGET_KIB)
        );
    }
}
