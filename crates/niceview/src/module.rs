//! The small ZMK module mxKeys writes into the config repo to show pictures on the
//! nice!view, and the settings it keeps there so the pictures can be edited again.
//!
//! Layout (all under [`DIR`], plus one entry in `zephyr/module.yml`):
//!
//! ```text
//! nice_view_art/
//!   mxkeys.json        settings (what each half shows, dithering options …)
//!   source/left.gif    the original pictures, so they can be re-processed
//!   CMakeLists.txt     adds src/*.c to ZMK when CONFIG_MXKEYS_NICE_VIEW_ART=y
//!   Kconfig            CONFIG_MXKEYS_NICE_VIEW_ART (default y with a display)
//!   src/art.c          shows the frames on top of ZMK's own status screen
//!   src/frames.c       the frames (generated)
//!   src/mxkeys_art.h
//!   README.md
//! ```
//!
//! ZMK's nice!view screen is left untouched: once the display is ready, an LVGL image
//! is placed on top of the stock art (right half) or over the whole screen. The work
//! is queued on ZMK's display work queue, like ZMK's own widgets, so LVGL is only used
//! from one thread. Animations pause while the keyboard is idle.

use serde::{Deserialize, Serialize};

use crate::lvgl;
use crate::render::{Area, Frame, Options};

pub const DIR: &str = "nice_view_art";
pub const MODULE_YML: &str = "zephyr/module.yml";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Mode {
    /// ZMK's own screen (no picture from mxKeys).
    Off,
    /// The right half's picture area (status strip stays visible).
    Art,
    /// The whole screen.
    Full,
}

impl Mode {
    pub fn area(self) -> Option<Area> {
        match self {
            Mode::Off => None,
            Mode::Art => Some(Area::Art),
            Mode::Full => Some(Area::Full),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct HalfArt {
    pub mode: Mode,
    /// File name inside `nice_view_art/source/`.
    pub source: Option<String>,
    pub options: Options,
}

impl Default for HalfArt {
    fn default() -> Self {
        HalfArt {
            mode: Mode::Off,
            source: None,
            options: Options::default(),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ArtConfig {
    pub version: u32,
    pub left: HalfArt,
    pub right: HalfArt,
    /// Flash budget per half, in KiB.
    pub budget_kib: u32,
}

impl Default for ArtConfig {
    fn default() -> Self {
        ArtConfig {
            version: 1,
            left: HalfArt::default(),
            right: HalfArt::default(),
            budget_kib: DEFAULT_BUDGET_KIB,
        }
    }
}

/// Default flash budget per half. The nice!nano's program area is 792 KiB; a Corne
/// half with the nice!view used ~430 KiB (left) / ~315 KiB (right) in our builds
/// (ZMK 4de3133), so 64 KiB leaves plenty of room for ZMK to grow.
pub const DEFAULT_BUDGET_KIB: u32 = 64;
pub const MAX_BUDGET_KIB: u32 = 192;

/// How many frames of `area` fit in `budget_kib`.
pub fn max_frames(area: Area, budget_kib: u32) -> usize {
    let (w, h) = area.upright_size();
    let probe = Frame {
        width: w,
        height: h,
        pixels: vec![],
        delay_ms: 0,
    };
    // Frame data + descriptor (~24 bytes) + pointer + delay.
    let per = lvgl::frame_bytes(&probe) + 32;
    ((budget_kib.min(MAX_BUDGET_KIB) as usize * 1024) / per).max(1)
}

