//! Serialisable views of a config repo for the frontend. Pure functions, unit-tested
//! without a webview.

use std::path::Path;

use serde::Serialize;
use zmk_config::build_yaml::{BuildMatrix, BuildTarget};
use zmk_config::keymap::{self, DefinitionKind};
use zmk_config::repo::{self, KeymapFile, RepoError, RepoFiles};

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RepoSummary {
    pub root: String,
    pub keymaps: Vec<KeymapSummary>,
    pub conf_files: Vec<String>,
    pub has_west_yml: bool,
    pub build: Option<BuildSummary>,
    /// Problems worth showing, in plain language.
    pub warnings: Vec<String>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct KeymapSummary {
    pub path: String,
    pub file_name: String,
    pub layers: Vec<LayerSummary>,
    pub behaviors: usize,
    pub macros: usize,
    pub combos: usize,
    pub conditional_layers: usize,
    pub parse_problems: Vec<String>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct LayerSummary {
    pub index: usize,
    pub title: String,
    pub node_name: String,
    pub bindings: Vec<String>,
    /// If set, the layer can't be edited in the app (e.g. generated by a macro).
    pub read_only_reason: Option<String>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BuildSummary {
    pub targets: Vec<TargetSummary>,
    pub keyboard_shields: Vec<String>,
    pub boards: Vec<String>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct TargetSummary {
    pub artifact_name: String,
    pub board: String,
    pub shields: Vec<String>,
    pub snippets: Vec<String>,
    pub studio: bool,
    pub nice_view: bool,
    pub settings_reset: bool,
}

impl From<&BuildTarget> for TargetSummary {
    fn from(t: &BuildTarget) -> Self {
        TargetSummary {
            artifact_name: t.default_artifact_name(),
            board: t.board.raw.clone(),
            shields: t.shields.clone(),
            snippets: t.snippets.clone(),
            studio: t.has_studio(),
            nice_view: t.has_nice_view(),
            settings_reset: t.is_settings_reset(),
        }
    }
}

impl From<&BuildMatrix> for BuildSummary {
    fn from(m: &BuildMatrix) -> Self {
        BuildSummary {
            targets: m.targets.iter().map(TargetSummary::from).collect(),
            keyboard_shields: m.keyboard_shields().into_iter().map(str::to_string).collect(),
            boards: m.boards().into_iter().map(|b| b.raw.clone()).collect(),
        }
    }
}

pub fn keymap_summary(file: &KeymapFile) -> KeymapSummary {
    let doc = &file.document;
    let km = &file.keymap;
    let count = |k: DefinitionKind| km.definitions.iter().filter(|d| d.kind == k).count();
    KeymapSummary {
        path: file.path.display().to_string(),
        file_name: file
            .path
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default(),
        layers: km
            .layers
            .iter()
            .map(|l| LayerSummary {
                index: l.index,
                title: l.title(),
                node_name: l.node_name.clone(),
                bindings: l
                    .bindings
                    .as_ref()
                    .map(|b| b.bindings.iter().map(|b| b.raw.clone()).collect())
                    .unwrap_or_default(),
                read_only_reason: match &l.bindings {
                    None => Some("this layer has no key list we can read".into()),
                    Some(b) => b.opaque_reason.clone(),
                },
            })
            .collect(),
        behaviors: count(DefinitionKind::Behavior),
        macros: count(DefinitionKind::Macro),
        combos: keymap::combos(doc).len(),
        conditional_layers: keymap::conditional_layers(doc).len(),
        parse_problems: doc
            .diagnostics
            .iter()
            .map(|d| {
                let line = doc.source()[..d.span.start].matches('\n').count() + 1;
                format!("line {line}: {}", d.message)
            })
            .collect(),
    }
}

pub fn load_repo(root: &Path) -> Result<RepoSummary, RepoError> {
    let files = RepoFiles::discover(root)?;
    let mut warnings = Vec::new();
    let mut keymaps = Vec::new();
    for p in &files.keymaps {
        match KeymapFile::load(p) {
            Ok(k) => keymaps.push(keymap_summary(&k)),
            Err(e) => warnings.push(e.to_string()),
        }
    }
    if files.keymaps.is_empty() {
        warnings.push("No keymap file found in the `config` folder.".into());
    }
    let build = match repo::load_build_matrix(&files) {
        Ok(m) => m.as_ref().map(BuildSummary::from),
        Err(e) => {
            warnings.push(e.to_string());
            None
        }
    };
    if files.build_yaml.is_none() {
        warnings.push("No build.yaml found — we'll work out what to build from your hardware.".into());
    }
    Ok(RepoSummary {
        root: files.root.display().to_string(),
        keymaps,
        conf_files: files.confs.iter().map(|p| p.display().to_string()).collect(),
        has_west_yml: files.west_yml.is_some(),
        build,
        warnings,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    #[test]
    fn summarises_fixture_repo() {
        let fixtures = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../crates/zmk-config/tests/fixtures");
        let dir = std::env::temp_dir().join(format!("mxkeys-summary-{}", std::process::id()));
        std::fs::create_dir_all(dir.join("config")).unwrap();
        std::fs::copy(fixtures.join("user_build.yaml"), dir.join("build.yaml")).unwrap();
        std::fs::copy(fixtures.join("advanced.keymap"), dir.join("config/corne.keymap")).unwrap();

        let s = load_repo(&dir).unwrap();
        assert_eq!(s.keymaps.len(), 1);
        let k = &s.keymaps[0];
        assert_eq!(k.layers.len(), 4);
        assert_eq!(k.layers[0].bindings.len(), 42);
        assert_eq!(
            (k.behaviors, k.macros, k.combos, k.conditional_layers),
            (3, 1, 2, 1)
        );
        let b = s.build.unwrap();
        assert_eq!(b.targets.len(), 5);
        assert!(b.targets[1].studio && b.targets[1].nice_view);
        assert!(s.warnings.is_empty(), "{:?}", s.warnings);

        let json = serde_json::to_value(&k.layers[0]).unwrap();
        assert!(json.get("readOnlyReason").is_some());
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
